import assert from "node:assert/strict";
import { readFile, writeFile, stat } from "node:fs/promises";
import { whiskies } from "../src/data/whiskies.ts";
import { whiskyImages } from "../src/data/whisky-images.ts";
const read=async(file)=>JSON.parse(await readFile(file,"utf8"));
const save=(file,data)=>writeFile(file,JSON.stringify(data,null,2)+"\n");
const previous=await read(".cache/catalog-before-laphroaig-25-2009.json");
const current=new Map(whiskies.map((item)=>[item.id,item]));
for(const item of previous)assert.deepEqual(current.get(item.id),item,`Existing item changed: ${item.id}`);
const id="laphroaig-25-cask-strength-2009";const item=current.get(id);
assert.equal(item.age,25);assert.equal(item.abv,51);assert.equal(item.caskStrength,true);
assert.equal(item.dailyshotPrice,undefined);assert.ok(item.dailyshotProduct);
assert.equal(whiskies.filter((entry)=>entry.id===id).length,1);
assert.ok((await stat(`public${whiskyImages[id].path}`)).size>500);
const recordPath="scripts/catalog-candidates/laphroaig-25-2009-integration.json";
const record=await read(recordPath);
Object.assign(record,{status:"integrated-verified",currentCount:whiskies.length,existingEntriesPreserved:previous.length,results:[{id,photo:whiskyImages[id].path,price:null}]});
await save(recordPath,record);
const inventoryPath="scripts/catalog-candidates/laphroaig-inventory.json";
const inventory=await read(inventoryPath);
for(const entry of inventory.entries)if(entry.name==="25 Year Old Cask Strength 2009")Object.assign(entry,{status:"integrated",runtimeId:id,integrationRecord:"laphroaig-25-2009-integration.json"});
inventory.runtimeSnapshot.checkedAt=new Date().toISOString();inventory.lastCatalogAudit="2026-11-11";
inventory.runtimeSnapshot.rawCount=whiskies.filter((item)=>item.brand==="Laphroaig").length;
inventory.runtimeSnapshot.expressions=whiskies.filter((item)=>item.brand==="Laphroaig").map((item)=>item.englishName);
await save(inventoryPath,inventory);
const nextPath="scripts/catalog-candidates/laphroaig-25-pre2011-next.json";
const next=await read(nextPath);next.checkedOn="2026-11-11";next.status="2009-integrated-2010-unresolved-2008-remains";
Object.assign(next.entries.find((entry)=>entry.year===2009),{status:"integrated-verified",integrationRecord:"laphroaig-25-2009-integration.json"});
Object.assign(next.entries.find((entry)=>entry.year===2010),{status:"deferred-annual-identity-unverified",photoReview:"All3sellerphotos inspected:2showboxonly,1shows51.9%700mlbottlewithwhitebox.NoannualdateorL1025codevisible.SameABVas2021;titlealoneinsufficient.Do not assertduplicateornewrelease.",localEvidence:[".cache/laphroaig-25-2010-candidate.jpg",".cache/laphroaig-25-2010-candidate-b.jpg",".cache/laphroaig-25-2010-candidate-c.jpg"]});
await save(nextPath,next);
console.log(JSON.stringify({preserved:previous.length,total:whiskies.length,id,photo:whiskyImages[id].path}));
