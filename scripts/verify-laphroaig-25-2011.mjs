import assert from "node:assert/strict";
import { readFile, writeFile, stat } from "node:fs/promises";
import { whiskies } from "../src/data/whiskies.ts";
import { whiskyImages } from "../src/data/whisky-images.ts";
const read=async(file)=>JSON.parse(await readFile(file,"utf8"));
const save=(file,data)=>writeFile(file,JSON.stringify(data,null,2)+"\n");
const previous=await read(".cache/catalog-before-laphroaig-25-2011.json");
const current=new Map(whiskies.map((item)=>[item.id,item]));
for(const item of previous)assert.deepEqual(current.get(item.id),item,`Existing item changed: ${item.id}`);
const id="laphroaig-25-cask-strength-2011";const item=current.get(id);
assert.equal(item.age,25);assert.equal(item.abv,48.6);assert.equal(item.caskStrength,true);
assert.equal(item.dailyshotPrice,undefined);assert.ok(item.dailyshotProduct);
assert.equal(whiskies.filter((entry)=>entry.id===id).length,1);
assert.ok((await stat(`public${whiskyImages[id].path}`)).size>500);
assert.notEqual(whiskyImages[id].path,whiskyImages["laphroaig-25-cask-strength-2016"].path);
assert.ok(!current.has("laphroaig-25-cask-strength-2012"));
const recordPath="scripts/catalog-candidates/laphroaig-25-2011-integration.json";
const record=await read(recordPath);
Object.assign(record,{status:"integrated-verified",currentCount:whiskies.length,existingEntriesPreserved:previous.length,results:[{id,photo:whiskyImages[id].path,price:null}]});
await save(recordPath,record);
const inventoryPath="scripts/catalog-candidates/laphroaig-inventory.json";
const inventory=await read(inventoryPath);
for(const entry of inventory.entries)if(entry.name==="25 Year Old Cask Strength 2011")Object.assign(entry,{status:"integrated",runtimeId:id,integrationRecord:"laphroaig-25-2011-integration.json"});
inventory.runtimeSnapshot.checkedAt=new Date().toISOString();inventory.lastCatalogAudit="2026-11-10";
inventory.runtimeSnapshot.rawCount=whiskies.filter((item)=>item.brand==="Laphroaig").length;
inventory.runtimeSnapshot.expressions=whiskies.filter((item)=>item.brand==="Laphroaig").map((item)=>item.englishName);
await save(inventoryPath,inventory);
const nextPath="scripts/catalog-candidates/laphroaig-25-2011-2012-next.json";
const next=await read(nextPath);next.status="2011-integrated-2012-identity-unresolved";
Object.assign(next.entries.find((entry)=>entry.year===2011),{status:"integrated-verified",integrationRecord:"laphroaig-25-2011-integration.json"});
Object.assign(next.entries.find((entry)=>entry.year===2012),{status:"deferred-annual-label-unverified",photoReview:"All threeSothebysphotos inspected: white wooden boxes48.6%70cl with no year on front/back/caps. Back label sayssecond-fillOloroso+Americanbourbon; differs from explicit2011blackbox, resembles2016. Cannot identify2012or assertduplicate from title alone.",localEvidence:[".cache/laphroaig-25-2012-sothebys-a.jpg",".cache/laphroaig-25-2012-sothebys-b.jpg",".cache/laphroaig-25-2012-sothebys-c.jpg"]});
await save(nextPath,next);
console.log(JSON.stringify({preserved:previous.length,total:whiskies.length,id,photo:whiskyImages[id].path}));
