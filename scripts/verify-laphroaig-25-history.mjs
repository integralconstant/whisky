import assert from "node:assert/strict";
import { readFile, writeFile, stat } from "node:fs/promises";
import { whiskies } from "../src/data/whiskies.ts";
import { whiskyImages } from "../src/data/whisky-images.ts";
const read = async (file) => JSON.parse(await readFile(file, "utf8"));
const save = (file, value) => writeFile(file, JSON.stringify(value, null, 2) + "\n");
const previous = await read(".cache/catalog-before-laphroaig-25-history.json");
const current = new Map(whiskies.map((item) => [item.id, item]));
for (const item of previous) assert.deepEqual(current.get(item.id), item, `Changed existing item ${item.id}`);
const id = "laphroaig-25-cask-strength-2017";
const item = current.get(id);
assert.equal(item.age, 25); assert.equal(item.abv, 48.9); assert.equal(item.caskStrength, true);
assert.equal(item.dailyshotPrice, undefined);
assert.ok(whiskyImages[id]);
assert.ok((await stat(`public${whiskyImages[id].path}`)).size > 500);
assert.equal(whiskies.filter((entry) => entry.id === id).length, 1);
const recordPath = "scripts/catalog-candidates/laphroaig-25-history-integration.json";
const record = await read(recordPath);
Object.assign(record, { status: "integrated-verified", currentCount: whiskies.length, existingEntriesPreserved: previous.length, results: [{ id, photo: whiskyImages[id].path, price: null }] });
await save(recordPath, record);
const inventoryPath = "scripts/catalog-candidates/laphroaig-inventory.json";
const inventory = await read(inventoryPath);
for (const entry of inventory.entries) if (entry.name === "25 Year Old Cask Strength 2017") Object.assign(entry, { status: "integrated", runtimeId: id, integrationRecord: "laphroaig-25-history-integration.json" });
inventory.runtimeSnapshot.checkedAt = new Date().toISOString();
inventory.lastCatalogAudit = "2026-11-10";
inventory.runtimeSnapshot.rawCount = whiskies.filter((entry) => entry.brand === "Laphroaig").length;
inventory.runtimeSnapshot.expressions = whiskies.filter((entry) => entry.brand === "Laphroaig").map((entry) => entry.englishName);
await save(inventoryPath, inventory);
const nextPath = "scripts/catalog-candidates/laphroaig-25-older-next.json";
const next = await read(nextPath);
next.entries.find((entry) => entry.year === 2017).status = "integrated-verified";
next.checkedOn = "2026-11-10";
await save(nextPath, next);
console.log(JSON.stringify({ preserved: previous.length, total: whiskies.length, photo: whiskyImages[id].path }));
