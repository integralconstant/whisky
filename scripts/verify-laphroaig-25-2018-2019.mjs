import assert from "node:assert/strict";
import { readFile, writeFile, stat } from "node:fs/promises";
import { whiskies } from "../src/data/whiskies.ts";
import { whiskyImages } from "../src/data/whisky-images.ts";
import { sellerReleaseMatches } from "./dailyshot-matching.mjs";
const read = async (file) => JSON.parse(await readFile(file, "utf8"));
const save = (file, value) => writeFile(file, JSON.stringify(value, null, 2) + "\n");
const previous = await read(".cache/catalog-before-laphroaig-25-2018-2019.json");
const current = new Map(whiskies.map((item) => [item.id, item]));
for (const item of previous) assert.deepEqual(current.get(item.id), item, `Existing item changed: ${item.id}`);
const mappings = await read("scripts/dailyshot-mappings.json");
const evidence = await read(".cache/laphroaig-25-offers.json");
const results = [];
for (const [year, abv] of [[2018, 52], [2019, 51.4]]) {
  const id = `laphroaig-25-cask-strength-${year}`;
  const item = current.get(id);
  assert.equal(item.age, 25); assert.equal(item.abv, abv); assert.equal(item.caskStrength, true);
  assert.equal(whiskies.filter((entry) => entry.id === id).length, 1);
  assert.ok((await stat(`public${whiskyImages[id].path}`)).size > 500);
  assert.ok(item.dailyshotProduct);
  if (year === 2018) {
    const matching = evidence.results.filter(({item:offer,seller}) => offer.status === 0 && seller.is_active && sellerReleaseMatches(item, mappings[id], offer));
    assert.equal(matching.length, 1); assert.equal(matching[0].item.id, 283631);
    assert.equal(item.dailyshotPrice.sampleCount, 1);
    assert.equal(item.dailyshotPrice.average, matching[0].item.price);
    assert.equal(item.dailyshotPrice.average, 1390000);
    assert.equal(item.dailyshotPrice.volumeMl, 700);
    assert.ok(item.dailyshotPrice.offers[0].url.includes("item=283631"));
  } else assert.equal(item.dailyshotPrice, undefined);
  results.push({ id, photo: whiskyImages[id].path, price: item.dailyshotPrice ?? null });
}
const recordPath = "scripts/catalog-candidates/laphroaig-25-2018-2019-integration.json";
const record = await read(recordPath);
Object.assign(record, { status: "integrated-verified", currentCount: whiskies.length, existingEntriesPreserved: previous.length, results });
await save(recordPath, record);
const inventoryPath = "scripts/catalog-candidates/laphroaig-inventory.json";
const inventory = await read(inventoryPath);
for (const entry of inventory.entries) for (const year of [2018,2019]) if(entry.name === `25 Year Old Cask Strength ${year}`) Object.assign(entry,{status:"integrated",runtimeId:`laphroaig-25-cask-strength-${year}`,integrationRecord:"laphroaig-25-2018-2019-integration.json"});
inventory.runtimeSnapshot.checkedAt = new Date().toISOString(); inventory.lastCatalogAudit = "2026-11-10";
inventory.runtimeSnapshot.rawCount = whiskies.filter((item) => item.brand === "Laphroaig").length;
inventory.runtimeSnapshot.expressions = whiskies.filter((item) => item.brand === "Laphroaig").map((item) => item.englishName);
await save(inventoryPath, inventory);
const nextPath = "scripts/catalog-candidates/laphroaig-25-older-next.json";
const next = await read(nextPath);
for(const entry of next.entries) if([2018,2019].includes(entry.year)) Object.assign(entry,{status:"integrated-verified",integrationRecord:"laphroaig-25-2018-2019-integration.json"});
next.status = "listed-2017-2019-integrated-earlier-and-newer-research-remains";
await save(nextPath, next);
const followupPath = "scripts/catalog-candidates/laphroaig-25-history-followup.json";
const followup = await read(followupPath);
for(const entry of followup.next) Object.assign(entry,{status:"integrated-verified",integrationRecord:"laphroaig-25-2018-2019-integration.json"});
followup.status="listed-2018-2019-integrated-newer-and-earlier-releases-remain";
await save(followupPath, followup);
console.log(JSON.stringify({preserved:previous.length,total:whiskies.length,results:results.map(({id,price})=>({id,average:price?.average??null}))}));
